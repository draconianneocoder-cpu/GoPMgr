const (
	beginMarker = "<!-- ledger:begin -->"
	endMarker   = "<!-- ledger:end -->"
)

func kindRank(k string) int {
	for i, v := range kinds {
		if v == k {
			return i
		}
	}
	return len(kinds)
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// shorten cuts s to at most n runes at a word boundary, marking the cut.
func shorten(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	cut := string(r[:n])
	if i := strings.LastIndex(cut, " "); i > n/2 {
		cut = cut[:i]
	}
	return strings.TrimRight(cut, " ,;:") + "…"
}

// renderLedgerView is docs/LEDGER.md: every entry, by folder.
func renderLedgerView(l *Ledger) string {
	var b strings.Builder
	b.WriteString("<!--\nSPDX-FileCopyrightText: 2026 James L. Burns and The GoPMgr Contributors\nSPDX-License-Identifier: GFDL-1.3-or-later\n-->\n\n")
	b.WriteString("# Documentation ledger\n\n")
	b.WriteString("Generated from [`ledger.json`](ledger.json) by `make docs-ledger`. Do not edit\n")
	b.WriteString("this file; edit the ledger and regenerate. The rules are in section 6 of the\n")
	b.WriteString("[reorganization plan](design/docs-reorganization-plan.md#6-documentation-ledger).\n")
	b.WriteString("Find a document by ID with `make docs-ledger find=DOC-0001`.\n")

	folders := map[string][]Entry{}
	var removed []Entry
	for _, e := range l.Entries {
		if e.Status == "removed" {
			removed = append(removed, e)
			continue
		}
		d := path.Dir(dirOf(e.Path))
		folders[d] = append(folders[d], e)
	}
	var names []string
	for d := range folders {
		names = append(names, d)
	}
	sort.Strings(names)
	for _, d := range names {
		es := folders[d]
		sort.Slice(es, func(i, j int) bool { return es[i].Path < es[j].Path })
		fmt.Fprintf(&b, "\n## `%s/`\n\n| ID | File | Kind | Status | Summary |\n| --- | --- | --- | --- | --- |\n", d)
		for _, e := range es {
			rel := strings.TrimPrefix(e.Path, "docs/")
			name := strings.TrimPrefix(e.Path, d+"/")
			fmt.Fprintf(&b, "| %s | [`%s`](%s) | %s | %s | %s |\n", e.ID, name, strings.TrimSuffix(rel, "**"), e.Kind, e.Status, cell(e.Summary))
		}
	}
	if len(removed) > 0 {
		sort.Slice(removed, func(i, j int) bool { return removed[i].ID < removed[j].ID })
		b.WriteString("\n## Removed documents\n\n| ID | Former path | Content now in | Evidence |\n| --- | --- | --- | --- |\n")
		for _, e := range removed {
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", e.ID, e.Path, e.ContentNowIn, e.StatusEvidence)
		}
	}
	if len(l.Planned) > 0 {
		b.WriteString("\n## Planned documents\n\n| Path | Promised by |\n| --- | --- |\n")
		for _, p := range l.Planned {
			fmt.Fprintf(&b, "| `%s` | `%s` |\n", p.Path, p.PromisedBy)
		}
	}
	return b.String()
}

// renderFolderList is the generated part of a folder README: the folder's
// own files, then its subfolders.
func renderFolderList(l *Ledger, folder string) string {
	var own []Entry
	sub := map[string]int{}
	for _, e := range l.Entries {
		if e.Status == "removed" || !strings.HasPrefix(e.Path, folder+"/") {
			continue
		}
		rest := strings.TrimPrefix(e.Path, folder+"/")
		// A file in a subfolder counts toward that subfolder; a data directory
		// directly in this folder is listed here.
		if i := strings.Index(rest, "/"); i >= 0 && (!isDirEntry(e.Path) || strings.Count(rest, "/") != 1) {
			sub[rest[:i]]++
			continue
		}
		own = append(own, e)
	}
	sort.Slice(own, func(i, j int) bool {
		if a, b := kindRank(own[i].Kind), kindRank(own[j].Kind); a != b {
			return a < b
		}
		return own[i].Path < own[j].Path
	})
	var b strings.Builder
	b.WriteString(beginMarker + "\n")
	b.WriteString("<!-- Generated by make docs-ledger from docs/ledger.json; do not edit by hand. -->\n\n")
	b.WriteString("| ID | File | Kind | Status | Summary |\n| --- | --- | --- | --- | --- |\n")
	for _, e := range own {
		rel := strings.TrimPrefix(e.Path, folder+"/")
		status := e.Status
		if e.StatedStatus != "" {
			status += " (" + cell(shorten(e.StatedStatus, 60)) + ")"
		}
		fmt.Fprintf(&b, "| %s | [`%s`](%s) | %s | %s | %s |\n", e.ID, rel, strings.TrimSuffix(rel, "**"), e.Kind, status, cell(e.Summary))
	}
	if len(sub) > 0 {
		var names []string
		for s := range sub {
			names = append(names, s)
		}
		sort.Strings(names)
		b.WriteString("\n| Folder | Documents |\n| --- | ---: |\n")
		for _, s := range names {
			fmt.Fprintf(&b, "| [`%s/`](%s/) | %d |\n", s, s, sub[s])
		}
	}
	b.WriteString(endMarker)
	return b.String()
}

// spliceList replaces the generated section of a README; ok is false when
// the README has no markers.
func spliceList(readme, list string) (string, bool) {
	i := strings.Index(readme, beginMarker)
	j := strings.Index(readme, endMarker)
	if i < 0 || j < i || strings.Count(readme, beginMarker) != 1 || strings.Count(readme, endMarker) != 1 {
		return readme, false
	}
	return readme[:i] + list + readme[j+len(endMarker):], true
}
