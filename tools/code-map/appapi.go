package main

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// appPackageDir holds the Wails-bound App. Its exported methods are the
// frontend's whole backend API (window.go.desktop.App).
const appPackageDir = "internal/desktop"

type appMethod struct {
	Method       string   `json:"method"`
	File         string   `json:"file"`
	Line         int      `json:"line"`
	Params       string   `json:"params"`
	Returns      string   `json:"returns"`
	UsesInternal []string `json:"uses_internal_packages"`
}

type appAPI struct {
	Description string      `json:"description"`
	Methods     []appMethod `json:"methods"`
}

// generateAppAPI lists every exported method on App, which Wails binds to
// the frontend, with its signature and the first-party internal packages
// its body refers to directly (not transitively).
func generateAppAPI(root string) ([]byte, error) {
	dir := filepath.Join(root, filepath.FromSlash(appPackageDir))
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, fmt.Errorf("list %s: %w", appPackageDir, err)
	}
	var methods []appMethod
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", name, err)
		}
		imports := internalImports(f)
		rel := path.Join(appPackageDir, filepath.Base(name))
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || !fn.Name.IsExported() || !isAppReceiver(fn.Recv) {
				continue
			}
			methods = append(methods, appMethod{
				Method:       fn.Name.Name,
				File:         rel,
				Line:         fset.Position(fn.Pos()).Line,
				Params:       fieldListString(fn.Type.Params),
				Returns:      fieldListString(fn.Type.Results),
				UsesInternal: usedPackages(fn.Body, imports),
			})
		}
	}
	if len(methods) == 0 {
		return nil, fmt.Errorf("no exported App methods found in %s", appPackageDir)
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Method < methods[j].Method })
	data, err := json.MarshalIndent(appAPI{
		Description: "Every exported method on the Wails-bound App (internal/desktop), callable from the frontend as window.go.desktop.App.<method>, with the first-party internal packages its body refers to directly. Generated by `make code-map`; `make verify` fails when it is stale.",
		Methods:     methods,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode app API map: %w", err)
	}
	return append(data, '\n'), nil
}

func isAppReceiver(recv *ast.FieldList) bool {
	if recv == nil || len(recv.List) != 1 {
		return false
	}
	t := recv.List[0].Type
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	id, ok := t.(*ast.Ident)
	return ok && id.Name == "App"
}

// internalImports maps each file-local import name of a first-party
// internal package to its import path. The default name is the last path
// element, which is the package name throughout this repository.
func internalImports(f *ast.File) map[string]string {
	out := map[string]string{}
	for _, spec := range f.Imports {
		p, err := strconv.Unquote(spec.Path.Value)
		if err != nil || !strings.HasPrefix(p, modulePath+"/internal/") {
			continue
		}
		name := path.Base(p)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		out[name] = p
	}
	return out
}

func usedPackages(body *ast.BlockStmt, imports map[string]string) []string {
	if body == nil {
		return []string{}
	}
	seen := map[string]bool{}
	ast.Inspect(body, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		// A package name is unresolved (Obj == nil); a local variable or
		// parameter that shares an import's name resolves to its declaration.
		if id, ok := sel.X.(*ast.Ident); ok && id.Obj == nil {
			if p, ok := imports[id.Name]; ok {
				seen[p] = true
			}
		}
		return true
	})
	out := make([]string, 0, len(seen))
	for p := range seen {
		out = append(out, p)
	}
	return uniqueSorted(out)
}

func fieldListString(fl *ast.FieldList) string {
	if fl == nil {
		return ""
	}
	var parts []string
	for _, field := range fl.List {
		typ := types.ExprString(field.Type)
		if len(field.Names) == 0 {
			parts = append(parts, typ)
			continue
		}
		for _, name := range field.Names {
			parts = append(parts, name.Name+" "+typ)
		}
	}
	return strings.Join(parts, ", ")
}
